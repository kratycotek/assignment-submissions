CREATE TABLE IF NOT EXISTS FCT_SALES (
    ITEM_KY              INTEGER NOT NULL REFERENCES DIM_ITEM (ITEM_KY),
    LOCN_KY              INTEGER NOT NULL REFERENCES DIM_LOCN (LOCN_KY),
    DAY_KY               INTEGER NOT NULL REFERENCES DIM_DAY (DAY_KY),
    CUSTOMER_KY          INTEGER NOT NULL REFERENCES DIM_CUSTOMER (CUSTOMER_KY),
    TRANSACTION_ID       INTEGER NOT NULL,
    TRANSACTION_LINE_NBR INTEGER NOT NULL,
    NET_SALES_AMT        DECIMAL(18,4) NOT NULL,
    QUANTITY_QTY         INTEGER NOT NULL,
    REC_INS_TS           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    REC_UPDT_TS          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    SRC_SYS_CD           STRING  NOT NULL,
    BATCH_ID             STRING  NOT NULL,
    PRIMARY KEY (ITEM_KY, LOCN_KY, DAY_KY, TRANSACTION_ID, TRANSACTION_LINE_NBR)
);

CREATE TABLE IF NOT EXISTS FCT_PRICE (
    ITEM_KY           INTEGER NOT NULL REFERENCES DIM_ITEM (ITEM_KY),
    LOCN_KY           INTEGER NOT NULL REFERENCES DIM_LOCN (LOCN_KY),
    DAY_KY            INTEGER NOT NULL REFERENCES DIM_DAY (DAY_KY),
    HOLDING_PRICE_AMT DECIMAL(18,4) NOT NULL,
    REC_INS_TS        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    REC_UPDT_TS       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    SRC_SYS_CD        STRING  NOT NULL,
    BATCH_ID          STRING  NOT NULL,
    EFF_FROM_DT       DATE    NOT NULL,
    EFF_TO_DT         DATE    DEFAULT DATE '9999-12-31' NOT NULL,
    PRIMARY KEY (ITEM_KY, LOCN_KY, DAY_KY)
);

CREATE TABLE IF NOT EXISTS FCT_INVENTORY (
    ITEM_KY             INTEGER NOT NULL REFERENCES DIM_ITEM (ITEM_KY),
    LOCN_KY             INTEGER NOT NULL REFERENCES DIM_LOCN (LOCN_KY),
    DAY_KY              INTEGER NOT NULL REFERENCES DIM_DAY (DAY_KY),
    ON_HAND_QTY         INTEGER NOT NULL,
    INVENTORY_VALUE_AMT DECIMAL(18,4) NOT NULL,
    RECEIVED_QTY        INTEGER DEFAULT 0 NOT NULL,
    REC_INS_TS          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    REC_UPDT_TS         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    SRC_SYS_CD          STRING  NOT NULL,
    BATCH_ID            STRING  NOT NULL,
    EFF_FROM_DT         DATE    NOT NULL,
    EFF_TO_DT           DATE    DEFAULT DATE '9999-12-31' NOT NULL,
    PRIMARY KEY (ITEM_KY, LOCN_KY, DAY_KY)
);

CREATE TABLE IF NOT EXISTS AGG_SALES_WEEKLY (
    ITEM_KY       INTEGER NOT NULL REFERENCES DIM_ITEM (ITEM_KY),
    LOCN_KY       INTEGER NOT NULL REFERENCES DIM_LOCN (LOCN_KY),
    WEEK_KY       INTEGER NOT NULL REFERENCES DIM_FISCAL_WEEK (WEEK_KY),
    NET_SALES_AMT DECIMAL(18,4) NOT NULL,
    QUANTITY_QTY  INTEGER NOT NULL,
    SRC_ROW_CNT   INTEGER NOT NULL,
    REC_INS_TS    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    REC_UPDT_TS   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    SRC_SYS_CD    STRING  NOT NULL,
    BATCH_ID      STRING  NOT NULL,
    EFF_FROM_DT   DATE    NOT NULL,
    EFF_TO_DT     DATE    DEFAULT DATE '9999-12-31' NOT NULL,
    PRIMARY KEY (ITEM_KY, LOCN_KY, WEEK_KY)
);
