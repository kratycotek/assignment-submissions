CREATE TABLE IF NOT EXISTS C_BATCH_SCRIPTS (
    SCRIPT_SEQ      INTEGER       NOT NULL PRIMARY KEY,
    SCRIPT_NM       STRING        NOT NULL,
    LAYER_CD        STRING        NOT NULL,
    TARGET_TBL_NM   STRING        NOT NULL,
    ENABLED_FLG     BOOLEAN       DEFAULT TRUE NOT NULL,
    REC_INS_TS      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    REC_UPDT_TS     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    CONSTRAINT UQ_C_BATCH_SCRIPTS_NM UNIQUE (SCRIPT_NM)
);

CREATE TABLE IF NOT EXISTS C_BATCH_LOG (
    LOG_ID          INTEGER IDENTITY(1,1) PRIMARY KEY,
    BATCH_ID        STRING        NOT NULL,
    BUSINESS_DT     DATE          NOT NULL,
    SCRIPT_NM       STRING        NOT NULL,
    SRC_TBL_NM      STRING,
    TGT_TBL_NM      STRING,
    STATUS_CD       STRING        NOT NULL,
    ROW_IN_CNT      INTEGER,
    ROW_OUT_CNT     INTEGER,
    ROW_REJ_CNT     INTEGER,
    START_TS        TIMESTAMP_NTZ,
    END_TS          TIMESTAMP_NTZ,
    ELAPSED_SEC     NUMBER(18,3),
    FAILURE_REASON  STRING,
    REC_INS_TS      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL
);

CREATE TABLE IF NOT EXISTS C_PARAM (
    BATCH_ID        STRING        NOT NULL,
    PARAM_NM        STRING        NOT NULL,
    PARAM_VAL       STRING,
    BUSINESS_DT     DATE,
    REC_INS_TS      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    CONSTRAINT PK_C_PARAM PRIMARY KEY (BATCH_ID, PARAM_NM)
);

CREATE TABLE IF NOT EXISTS C_REJ_TABLE (
    REJ_ID            INTEGER IDENTITY(1,1) PRIMARY KEY,
    FAILED_LAYER_CD   STRING        NOT NULL,
    SOURCE_STAGE      STRING        NOT NULL,
    GATE_ID           STRING        NOT NULL,
    REASON_CD         STRING        NOT NULL,
    SRC_TABLE_NM      STRING,
    BATCH_ID          STRING        NOT NULL,
    SRC_FILE_NM       STRING,
    PAYLOAD           VARIANT,
    REC_INS_TS        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL
);

CREATE TABLE IF NOT EXISTS C_ALERT_TABLE (
    ALERT_ID          INTEGER IDENTITY(1,1) PRIMARY KEY,
    FAILED_LAYER_CD   STRING        NOT NULL,
    SOURCE_STAGE      STRING        NOT NULL,
    GATE_ID           STRING        NOT NULL,
    REASON_CD         STRING        NOT NULL,
    SRC_TABLE_NM      STRING,
    BATCH_ID          STRING        NOT NULL,
    SRC_FILE_NM       STRING,
    PAYLOAD           VARIANT,
    REC_INS_TS        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL
);

CREATE TABLE IF NOT EXISTS C_LOAD_DATES (
    TARGET_TBL_NM   STRING        NOT NULL PRIMARY KEY,
    LAST_LOAD_DT    DATE          NOT NULL,
    BATCH_ID        STRING        NOT NULL,
    REC_UPDT_TS     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP() NOT NULL
);
