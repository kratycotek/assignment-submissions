INSERT INTO DIM_FISCAL_YEAR (YEAR_ID)
WITH day_range AS (
    SELECT DATEADD(DAY, SEQ4(), DATE '2020-01-01') AS d
    FROM TABLE(GENERATOR(ROWCOUNT => 5000))
)
SELECT DISTINCT YEAR(r.d)
FROM day_range AS r
WHERE r.d <= DATE '2030-12-31'
  AND NOT EXISTS (SELECT 1 FROM DIM_FISCAL_YEAR AS y WHERE y.YEAR_ID = YEAR(r.d));

INSERT INTO DIM_FISCAL_MONTH (MONTH_ID, MONTH_NBR, QUARTER_NBR, YEAR_KY)
WITH day_range AS (
    SELECT DATEADD(DAY, SEQ4(), DATE '2020-01-01') AS d
    FROM TABLE(GENERATOR(ROWCOUNT => 5000))
)
SELECT DISTINCT
    YEAR(r.d) * 100 + MONTH(r.d) AS month_id,
    MONTH(r.d) AS month_nbr,
    QUARTER(r.d) AS quarter_nbr,
    y.YEAR_KY
FROM day_range AS r
JOIN DIM_FISCAL_YEAR AS y ON y.YEAR_ID = YEAR(r.d)
WHERE r.d <= DATE '2030-12-31'
  AND NOT EXISTS (
      SELECT 1 FROM DIM_FISCAL_MONTH AS m
      WHERE m.MONTH_ID = YEAR(r.d) * 100 + MONTH(r.d)
  );

INSERT INTO DIM_FISCAL_WEEK (WEEK_ID, WEEK_START_DT, WEEK_END_DT, MONTH_KY)
WITH day_range AS (
    SELECT DATEADD(DAY, SEQ4(), DATE '2020-01-01') AS d
    FROM TABLE(GENERATOR(ROWCOUNT => 5000))
),
weeks AS (
    SELECT DISTINCT DATE_TRUNC('WEEK', r.d) AS wk_start_dt
    FROM day_range AS r
    WHERE r.d <= DATE '2030-12-31'
)
SELECT
    TO_NUMBER(TO_CHAR(w.wk_start_dt, 'YYYYMMDD')) AS week_id,
    w.wk_start_dt,
    DATEADD(DAY, 6, w.wk_start_dt) AS week_end_dt,
    m.MONTH_KY
FROM weeks AS w
JOIN DIM_FISCAL_MONTH AS m
  ON m.MONTH_ID = YEAR(w.wk_start_dt) * 100 + MONTH(w.wk_start_dt)
WHERE NOT EXISTS (
    SELECT 1 FROM DIM_FISCAL_WEEK AS f
    WHERE f.WEEK_START_DT = w.wk_start_dt
);

INSERT INTO DIM_DAY (DAY_ID, CALENDAR_DT, DAY_OF_WEEK_NAME, HOLIDAY_FLG, WEEK_KY)
WITH day_range AS (
    SELECT DATEADD(DAY, SEQ4(), DATE '2020-01-01') AS d
    FROM TABLE(GENERATOR(ROWCOUNT => 5000))
)
SELECT
    TO_NUMBER(TO_CHAR(r.d, 'YYYYMMDD')) AS day_id,
    r.d AS calendar_dt,
    DAYNAME(r.d) AS day_of_week_name,
    FALSE AS holiday_flg,
    w.WEEK_KY
FROM day_range AS r
JOIN DIM_FISCAL_WEEK AS w ON w.WEEK_START_DT = DATE_TRUNC('WEEK', r.d)
WHERE r.d <= DATE '2030-12-31'
  AND NOT EXISTS (SELECT 1 FROM DIM_DAY AS x WHERE x.CALENDAR_DT = r.d);
