INSERT INTO DIM_FISCAL_YEAR (YEAR_ID)
SELECT DISTINCT YEAR(d)
FROM (SELECT DATEADD(DAY, SEQ4(), $START_DT::DATE) AS d
      FROM TABLE(GENERATOR(ROWCOUNT => $CAL_ROWCOUNT)))
WHERE d <= $END_DT::DATE
ORDER BY 1;

INSERT INTO DIM_FISCAL_MONTH (MONTH_ID, MONTH_NBR, QUARTER_NBR, YEAR_KY)
SELECT DISTINCT
    YEAR(d) * 100 + MONTH(d) AS MONTH_ID,
    MONTH(d)                 AS MONTH_NBR,
    QUARTER(d)               AS QUARTER_NBR,
    y.YEAR_KY
FROM (SELECT DATEADD(DAY, SEQ4(), $START_DT::DATE) AS d
      FROM TABLE(GENERATOR(ROWCOUNT => $CAL_ROWCOUNT)))
JOIN DIM_FISCAL_YEAR y ON y.YEAR_ID = YEAR(d)
WHERE d <= $END_DT::DATE
ORDER BY 1;

INSERT INTO DIM_FISCAL_WEEK (WEEK_ID, WEEK_START_DT, WEEK_END_DT, MONTH_KY)
SELECT
    TO_NUMBER(TO_CHAR(wk_start_dt, 'YYYYMMDD')) AS WEEK_ID,
    wk_start_dt,
    DATEADD(DAY, 6, wk_start_dt)                AS WEEK_END_DT,
    m.MONTH_KY
FROM (SELECT DISTINCT DATE_TRUNC('WEEK',
             DATEADD(DAY, SEQ4(), $START_DT::DATE)) AS wk_start_dt
      FROM TABLE(GENERATOR(ROWCOUNT => $CAL_ROWCOUNT)))
JOIN DIM_FISCAL_MONTH m
  ON m.MONTH_ID = YEAR(wk_start_dt) * 100 + MONTH(wk_start_dt)
WHERE wk_start_dt <= $END_DT::DATE
ORDER BY wk_start_dt;

INSERT INTO DIM_DAY (DAY_ID, CALENDAR_DT, DAY_OF_WEEK_NAME, HOLIDAY_FLG, WEEK_KY)
SELECT
    TO_NUMBER(TO_CHAR(d.cal_dt, 'YYYYMMDD')) AS DAY_ID,
    d.cal_dt                                 AS CALENDAR_DT,
    DAYNAME(d.cal_dt)                        AS DAY_OF_WEEK_NAME,
    FALSE                                    AS HOLIDAY_FLG,
    w.WEEK_KY
FROM (SELECT DATEADD(DAY, SEQ4(), $START_DT::DATE) AS cal_dt
      FROM TABLE(GENERATOR(ROWCOUNT => $CAL_ROWCOUNT))) d
JOIN DIM_FISCAL_WEEK w ON w.WEEK_START_DT = DATE_TRUNC('WEEK', d.cal_dt)
WHERE d.cal_dt <= $END_DT::DATE
ORDER BY d.cal_dt;

